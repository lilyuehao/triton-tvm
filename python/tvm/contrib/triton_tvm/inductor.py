@dataclass(frozen=True)
class TritonTVMInductorConfig:
    """Configuration for the experimental M5 TorchInductor hook.

    This is not a stable ABI.  M5 keeps the surface narrow: only native fallback
    and the existing ``pointwise_flat`` contract are supported.
    """

    fallback: str = "native"
    target: str = "cuda"
    passes: tuple[Any, ...] = ()
    report_dir: str | Path | None = None


@dataclass
class TritonTVMInductorSession:
    """State for one experimental M5 Inductor integration session."""

    config: TritonTVMInductorConfig = field(default_factory=TritonTVMInductorConfig)
    artifacts: dict[str, TritonTVMArtifact] = field(default_factory=dict)
    records: list[dict[str, Any]] = field(default_factory=list)
    graphs: list[dict[str, Any]] = field(default_factory=list)
    collection_errors: list[dict[str, Any]] = field(default_factory=list)
    private_api_guard: dict[str, Any] = field(default_factory=dict)
    counters: Counter = field(default_factory=Counter)
    _active_graphs: list[dict[str, Any]] = field(
        default_factory=list, init=False, repr=False
    )

    def __post_init__(self) -> None:
        if self.config.fallback != "native":
            raise ValueError(
                "M5 Triton TVM Inductor hook only supports fallback='native'"
            )

    def begin_graph(self, *, compile_region_name: str = "") -> dict[str, Any]:
        """Start a graph-level report record for one wrapped Inductor compile."""
        graph = {
            "graph_id": f"graph_{len(self.graphs)}",
            "compile_region_name": compile_region_name,
            "status": "compiling",
            "total_kernels": 0,
            "translated_kernels": 0,
            "native_fallback_kernels": 0,
            "cache_hits": 0,
            "cache_misses": 0,
            "run_count": 0,
            "fallback_reasons": {},
            "kernel_names": [],
            "kernel_record_indices": [],
        }
        self.graphs.append(graph)
        self._active_graphs.append(graph)
        self.counters["graphs_started"] += 1
        return graph

    def end_graph(
        self,
        graph: dict[str, Any],
        *,
        ok: bool,
        err: Exception | None = None,
    ) -> None:
        """Finish a graph-level report record."""
        if self._active_graphs and self._active_graphs[-1] is graph:
            self._active_graphs.pop()
        elif graph in self._active_graphs:
            self._active_graphs.remove(graph)
        graph["status"] = "completed" if ok else "internal_error"
        if err is not None:
            graph["error_type"] = type(err).__name__
            graph["message"] = str(err)
        self.counters["graphs_completed" if ok else "graphs_failed"] += 1
        self.write_report()

    def compile_triton(
        self,
        async_compile,
        original_triton,
        kernel_name: str,
        source_code: str,
        device_str: str = "cuda",
    ):
        """Compile one Inductor Triton kernel or return native fallback.

        ``original_triton`` is the unpatched ``AsyncCompile.triton`` method.  It
        is called only when this prototype cannot produce a TVM-backed kernel.
        """
        source = InductorTritonSource(
            case_name=kernel_name,
            kernel_name=kernel_name,
            source=source_code,
            device_str=device_str,
        )
        try:
            tvm_kernel = self._try_compile_tvm_kernel(
                source,
                async_compile=async_compile,
                original_triton=original_triton,
            )
        except Exception as err:  # pylint: disable=broad-except
            self._record_fallback(source, status_from_exception(err))
            return original_triton(async_compile, kernel_name, source_code, device_str)
        if tvm_kernel is None:
            return original_triton(async_compile, kernel_name, source_code, device_str)
        return tvm_kernel

    def report(self) -> dict[str, Any]:
        """Return the current M5 hook report using the shared capability schema."""
        report = build_capability_report(
            self.records,
            purpose="m5 inductor integration prototype",
            corpus="m5_inductor_hook",
            errors=self.collection_errors,
        )
        report["artifact_cache_size"] = len(self.artifacts)
        report["counters"] = dict(sorted(self.counters.items()))
        report["graph_summary"] = self._graph_summary()
        report["graphs"] = [_jsonable(dict(graph)) for graph in self.graphs]
        report["private_api_guard"] = _jsonable(dict(self.private_api_guard))
        report["runtime_counter_policy"] = _m5_runtime_counter_policy()
        report["report_flush_policy"] = "eager_when_report_dir_set"
        return report

    def write_report(self, out_dir: str | Path | None = None) -> None:
        """Write ``report.json`` and ``report.md`` for the current session."""
        report_dir = out_dir if out_dir is not None else self.config.report_dir
        if report_dir is None:
            return
        write_capability_report(
            self.report(),
            report_dir,
            markdown_title="M5 Inductor Integration Prototype",
            footer_lines=_m5_boundary_lines(),
        )

    def _try_compile_tvm_kernel(
        self,
        source: InductorTritonSource,
        *,
        async_compile,
        original_triton,
    ):
        kernel = load_inductor_kernel(source)
        if not is_inductor_pointwise_kernel(kernel):
            status = make_report_status(
                ok=False,
                bucket="contract_error",
                fallback_reason="unsupported_inductor_kernel",
                message=(
                    "M5 supports only Grid1D non-atomic pointwise Inductor "
                    "kernels through TVM"
                ),
            )
            self._record_fallback(source, status, kernel=kernel)
            return None

        artifact = lower_inductor_kernel_to_ttir(kernel)
        irmod, meta = translate_ttir(
            artifact,
            grid=(1,),
            target=self.config.target,
            contract="pointwise_flat",
        )
        cache_hit = meta.cache_key in self.artifacts
        if cache_hit:
            built = self.artifacts[meta.cache_key]
            self.counters["cache_hits"] += 1
        else:
            built = build_triton_tvm(
                irmod,
                meta,
                passes=self.config.passes,
                target=self.config.target,
            )
            self.artifacts[meta.cache_key] = built
            self.counters["cache_misses"] += 1

        record = self._record_translated(
            kernel=kernel,
            artifact=artifact,
            built=built,
            cache_hit=cache_hit,
        )
        return _TritonTVMInductorKernel(
            session=self,
            record=record,
            artifact=built,
            async_compile=async_compile,
            original_triton=original_triton,
            kernel_name=source.kernel_name,
            source_code=source.source,
            device_str=source.device_str,
        )

    def _record_translated(
        self,
        *,
        kernel: InductorKernel,
        artifact: TTIRArtifact,
        built: TritonTVMArtifact,
        cache_hit: bool,
    ) -> dict[str, Any]:
        try:
            coverage = _graph_coverage(TTIRReader().read(artifact.ttir))
        except Exception:  # pylint: disable=broad-except
            coverage = {}
        record = _base_m5_record(
            kernel_name=kernel.kernel_name,
            source=kernel.source,
            signature=kernel.signature,
            constexprs=kernel.constexprs,
            status=make_report_status(ok=True, bucket="translated"),
        )
        record.update(coverage)
        record.update(
            {
                "ttir_hash": _sha256(artifact.ttir),
                "cache_key": built.meta.cache_key,
                "cache_hit": bool(cache_hit),
                "cache_policy": built.meta.cache_policy,
                "disk_cache_enabled": built.meta.disk_cache_enabled,
                "run_count": 0,
                "native_fallback_count": 0,
            }
        )
        self._attach_record_to_graph(record, translated=True, cache_hit=cache_hit)
        self.records.append(record)
        self.counters["translated"] += 1
        self.write_report()
        return record

    def _record_fallback(
        self,
        source: InductorTritonSource,
        status: dict[str, Any],
        *,
        kernel: InductorKernel | None = None,
    ) -> dict[str, Any]:
        signature = kernel.signature if kernel is not None else {}
        constexprs = kernel.constexprs if kernel is not None else {}
        record = _base_m5_record(
            kernel_name=source.kernel_name,
            source=source.source,
            signature=signature,
            constexprs=constexprs,
            status=status,
        )
        if kernel is not None:
            record.update(
                {
                    "grid_type": kernel.inductor_meta.get("grid_type"),
                    "num_reduction": kernel.inductor_meta.get("num_reduction"),
                    "atomic_add_found": kernel.inductor_meta.get("atomic_add_found"),
                }
            )
        record["native_fallback_count"] = 1
        self._attach_record_to_graph(record, translated=False, cache_hit=False)
        self.records.append(record)
        self.counters["native_fallbacks"] += 1
        self.write_report()
        return record

    def _record_run(self, record: dict[str, Any]) -> None:
        record["run_count"] = int(record.get("run_count", 0)) + 1
        graph = self._graph_by_id(record.get("graph_id", ""))
        if graph is not None:
            graph["run_count"] = int(graph.get("run_count", 0)) + 1
        self.counters["runs"] += 1
        self.write_report()

    def _attach_record_to_graph(
        self,
        record: dict[str, Any],
        *,
        translated: bool,
        cache_hit: bool,
    ) -> None:
        graph = self._current_graph()
        if graph is None:
            return
        record_index = len(self.records)
        record["graph_id"] = graph["graph_id"]
        record["graph_kernel_index"] = len(graph["kernel_names"])
        graph["total_kernels"] += 1
        graph["kernel_names"].append(record["kernel_name"])
        graph["kernel_record_indices"].append(record_index)
        if translated:
            graph["translated_kernels"] += 1
            if cache_hit:
                graph["cache_hits"] += 1
            else:
                graph["cache_misses"] += 1
        else:
            graph["native_fallback_kernels"] += 1
            status = record.get("translate_status", {})
            reason = status.get("fallback_reason") or status.get("bucket", "unknown")
            fallback_reasons = graph["fallback_reasons"]
            fallback_reasons[reason] = int(fallback_reasons.get(reason, 0)) + 1

    def _current_graph(self) -> dict[str, Any] | None:
        return self._active_graphs[-1] if self._active_graphs else None

    def _graph_by_id(self, graph_id: str) -> dict[str, Any] | None:
        if not graph_id:
            return None
        return next(
            (graph for graph in self.graphs if graph["graph_id"] == graph_id),
            None,
        )

    def _record_private_api_guard(self, guard: dict[str, Any]) -> None:
        self.private_api_guard.update(_jsonable(dict(guard)))
        self.private_api_guard["ok"] = True
        self.counters["private_api_guard_checks"] += 1

    def _record_private_api_guard_error(self, err: Exception) -> None:
        status = status_from_exception(err)
        entry = {
            "stage": "private_api_guard",
            "bucket": status["bucket"],
            "fallback_reason": status["fallback_reason"],
            "error_type": status.get("error_type", type(err).__name__),
            "message": status.get("message", str(err)),
        }
        self.collection_errors.append(entry)
        self.private_api_guard = {"ok": False, **entry}
        self.counters["private_api_guard_failures"] += 1
        self.write_report()

    def _graph_summary(self) -> dict[str, Any]:
        return {
            "total_graphs": len(self.graphs),
            "completed_graphs": sum(
                1 for graph in self.graphs if graph["status"] == "completed"
            ),
            "failed_graphs": sum(
                1 for graph in self.graphs if graph["status"] == "internal_error"
            ),
            "total_kernels": sum(
                int(graph.get("total_kernels", 0)) for graph in self.graphs
            ),
            "translated_kernels": sum(
                int(graph.get("translated_kernels", 0)) for graph in self.graphs
            ),
            "native_fallback_kernels": sum(
                int(graph.get("native_fallback_kernels", 0)) for graph in self.graphs
            ),
            "cache_hits": sum(int(graph.get("cache_hits", 0)) for graph in self.graphs),
            "cache_misses": sum(int(graph.get("cache_misses", 0)) for graph in self.graphs),
            "run_count": sum(int(graph.get("run_count", 0)) for graph in self.graphs),
        }


