def extract_inductor_triton_sources(
    wrapper_source: str,
    *,
    case_name: str = "",
    wrapper_path: str = "",
) -> list[InductorTritonSource]:
    """Extract ``async_compile.triton(name, source, ...)`` calls from wrapper code."""
    tree = ast.parse(wrapper_source)
    sources: list[InductorTritonSource] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not _is_triton_compile_call(node):
            continue
        if len(node.args) < 2:
            continue
        kernel_name = _literal_string(node.args[0])
        source = _literal_string(node.args[1])
        if not kernel_name or not source:
            continue
        device_str = "cuda"
        for keyword in node.keywords:
            if keyword.arg == "device_str":
                device_str = _literal_string(keyword.value) or device_str
        sources.append(
            InductorTritonSource(
                case_name=case_name or kernel_name,
                kernel_name=kernel_name,
                source=source,
                device_str=device_str,
                wrapper_path=wrapper_path,
            )
        )
    return sources


def extract_inductor_wrapper_extern_calls(
    wrapper_source: str,
    *,
    case_name: str = "",
    wrapper_path: str = "",
) -> list[InductorWrapperExternCall]:
    """Extract wrapper-level extern/ATen calls that are not Triton kernels."""
    tree = ast.parse(wrapper_source)
    lines = wrapper_source.splitlines()
    calls: list[InductorWrapperExternCall] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        op_name = _attribute_chain(node.func)
        op_family = _wrapper_extern_family(op_name)
        if not op_family:
            continue
        line_no = int(getattr(node, "lineno", 0) or 0)
        source_line = lines[line_no - 1].strip() if 0 < line_no <= len(lines) else ""
        calls.append(
            InductorWrapperExternCall(
                case_name=case_name,
                op_name=op_name,
                op_family=op_family,
                line_no=line_no,
                wrapper_path=wrapper_path,
                source=source_line,
            )
        )
    return sorted(calls, key=lambda call: (call.line_no, call.op_name))


def _attribute_chain(node: ast.AST) -> str:
    parts: list[str] = []
    current: ast.AST | None = node
    while isinstance(current, ast.Attribute):
        parts.append(current.attr)
        current = current.value
    if isinstance(current, ast.Name):
        parts.append(current.id)
    else:
        return ""
    return ".".join(reversed(parts))


def _wrapper_extern_family(op_name: str) -> str:
    if op_name in {"extern_kernels.mm", "extern_kernels.bmm"}:
        return "extern_gemm"
    if op_name == "extern_kernels.addmm":
        return "extern_addmm_bias"
    if op_name == "extern_kernels.convolution":
        return "deferred_convolution"
    if op_name == "torch.ops.aten._scaled_dot_product_efficient_attention.default":
        return "deferred_attention"
    return ""


def load_inductor_kernel(
    source: InductorTritonSource | str,
    *,
    kernel_name: str | None = None,
    case_name: str = "",
    device_str: str = "cuda",
) -> InductorKernel:
    """Load an Inductor Triton source block through PyTorch's ``PyCodeCache``."""
    if isinstance(source, InductorTritonSource):
        kernel_name = source.kernel_name
        case_name = source.case_name
        device_str = source.device_str
        source_code = source.source
    else:
        source_code = source
        kernel_name = kernel_name or _first_triton_jit_function_name(source_code)
        case_name = case_name or kernel_name

    if not kernel_name:
        raise ValueError("Cannot load Inductor Triton source without a kernel name")

    from torch._inductor.codecache import PyCodeCache  # pylint: disable=import-outside-toplevel

    key, path = PyCodeCache.write(source_code)
    module = PyCodeCache.load_by_key_path(key, path, attrs={})
    kernel = getattr(module, kernel_name)
    triton_meta = dict(getattr(kernel, "triton_meta", {}) or {})
    inductor_meta = dict(getattr(kernel, "inductor_meta", {}) or {})
    configs = list(getattr(kernel, "configs", []) or [])
    constexprs = dict(getattr(configs[0], "kwargs", {}) if configs else {})
    signature = dict(triton_meta.get("signature", {}) or {})
    attrs = None
    if configs and hasattr(kernel, "_create_compile_meta"):
        compile_meta = kernel._create_compile_meta(configs[0])  # pylint: disable=protected-access
        signature = dict(compile_meta.get("signature", signature))
        constexprs = dict(compile_meta.get("constants", constexprs))
        attrs = compile_meta.get("configs", [None])[0]

    return InductorKernel(
        case_name=case_name,
        kernel_name=kernel_name,
        source=source_code,
        device_str=device_str,
        fn=getattr(kernel, "fn", kernel),
        signature=signature,
        constexprs=constexprs,
        attrs=attrs,
        triton_meta=triton_meta,
        inductor_meta=inductor_meta,
        size_hints=dict(getattr(kernel, "size_hints", {}) or {}),
    )


def is_inductor_pointwise_kernel(kernel: InductorKernel) -> bool:
    """Return whether a loaded kernel matches the M3 pointwise audit filter."""
    meta = kernel.inductor_meta
    return (
        "triton_heuristics.pointwise" in kernel.source
        and meta.get("grid_type") == "Grid1D"
        and int(meta.get("num_reduction", 0) or 0) == 0
        and not bool(meta.get("atomic_add_found", False))
    )


def lower_inductor_kernel_to_ttir(
    kernel: InductorKernel,
    *,
    dump_path: str | Path | None = None,
) -> TTIRArtifact:
    """Lower a loaded Inductor Triton kernel to optimized TTIR."""
    if kernel.device_str == "cuda":
        from torch._inductor.runtime import (  # pylint: disable=import-outside-toplevel
            triton_helpers,
        )

        triton_helpers.set_driver_to_gpu()
    return lower_to_ttir(
        kernel.fn,
        kernel.signature,
        kernel.constexprs,
        dump_path=dump_path,
        attrs=kernel.attrs,
    )


def make_triton_tvm_inductor_backend(
    config: TritonTVMInductorConfig | TritonTVMInductorSession | None = None,
):
    """Return an experimental backend callable for ``torch.compile``.

    The returned object has a ``triton_tvm_session`` attribute so tests and
    debugging tools can inspect reports and the process-local artifact cache.
    """
    if isinstance(config, TritonTVMInductorSession):
        session = config
    else:
        session = TritonTVMInductorSession(config or TritonTVMInductorConfig())

    def triton_tvm_inductor_backend(model_, example_inputs_, **kwargs):
        try:
            import torch  # pylint: disable=import-outside-toplevel
            import triton  # pylint: disable=import-outside-toplevel
            from torch._inductor.async_compile import (  # pylint: disable=import-outside-toplevel
                AsyncCompile,
            )
            import torch._inductor.compile_fx as compile_fx_mod  # pylint: disable=import-outside-toplevel

            session._record_private_api_guard(  # pylint: disable=protected-access
                _validate_torch_inductor_private_api(
                    torch_module=torch,
                    compile_fx=compile_fx_mod.compile_fx,
                    triton_module=triton,
                )
            )
            original_triton = _install_async_compile_triton_hook(AsyncCompile, session)
        except ImportError as err:
            guard_err = ValueError(
                "triton_tvm_inductor_private_api_guard: PyTorch, TorchInductor, "
                f"and Triton must be importable before installing the hook: {err}"
            )
            _record_private_api_guard_error_once(session, guard_err)
            raise guard_err from err
        except Exception as err:
            _record_private_api_guard_error_once(session, err)
            raise

        graph = session.begin_graph(
            compile_region_name=str(kwargs.get("compile_region_name", ""))
        )
        try:
            result = compile_fx_mod.compile_fx(model_, example_inputs_, **kwargs)
        except Exception as err:
            session.end_graph(graph, ok=False, err=err)
            raise
        else:
            session.end_graph(graph, ok=True)
            return result
        finally:
            _restore_async_compile_triton_hook(AsyncCompile, original_triton)

    triton_tvm_inductor_backend.__name__ = "triton_tvm_inductor_backend"
    triton_tvm_inductor_backend.triton_tvm_session = session
    return triton_tvm_inductor_backend


def _install_async_compile_triton_hook(async_compile_cls, session: TritonTVMInductorSession):
    global _ACTIVE_HOOK  # pylint: disable=global-statement

    try:
        session._record_private_api_guard(  # pylint: disable=protected-access
            _validate_async_compile_triton_api(async_compile_cls)
        )
    except Exception as err:
        _record_private_api_guard_error_once(session, err)
        raise

    _HOOK_LOCK.acquire()
    original_triton = async_compile_cls.triton
    if _ACTIVE_HOOK is not None or getattr(original_triton, "_triton_tvm_hook", False):
        _HOOK_LOCK.release()
        raise RuntimeError(
            "triton_tvm_inductor_hook_reentrant_compile: AsyncCompile.triton is "
            "already patched by an active Triton TVM Inductor session"
        )

    def patched_triton(async_compile, kernel_name, source_code, device_str="cuda"):
        return session.compile_triton(
            async_compile,
            original_triton,
            kernel_name,
            source_code,
            device_str,
        )

    patched_triton._triton_tvm_hook = True  # type: ignore[attr-defined]
    _ACTIVE_HOOK = {"session": session, "original_triton": original_triton}
    async_compile_cls.triton = patched_triton
    return original_triton


def _restore_async_compile_triton_hook(async_compile_cls, original_triton) -> None:
    global _ACTIVE_HOOK  # pylint: disable=global-statement

    try:
        async_compile_cls.triton = original_triton
        _ACTIVE_HOOK = None
    finally:
        _HOOK_LOCK.release()


def _validate_torch_inductor_private_api(
    *,
    torch_module,
    compile_fx,
    triton_module,
) -> dict[str, Any]:
    torch_compile = getattr(torch_module, "compile", None)
    if not callable(torch_compile):
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: torch.compile must be callable"
        )
    if not callable(compile_fx):
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: torch._inductor.compile_fx.compile_fx "
            "must be callable"
        )

    torch_version = str(getattr(torch_module, "__version__", ""))
    triton_version = str(getattr(triton_module, "__version__", ""))
    if not torch_version or not triton_version:
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: torch and triton versions must "
            f"be discoverable, got torch={torch_version!r}, triton={triton_version!r}"
        )

    return {
        "torch_compile": "callable",
        "torch_inductor_compile_fx": "callable",
        "torch_version": torch_version,
        "torch_inductor_version": torch_version,
        "triton_version": triton_version,
    }


def _validate_async_compile_triton_api(async_compile_cls) -> dict[str, Any]:
    original_triton = getattr(async_compile_cls, "triton", None)
    if not callable(original_triton):
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: AsyncCompile.triton must be callable"
        )
    try:
        signature = inspect.signature(original_triton)
    except (TypeError, ValueError) as err:
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: AsyncCompile.triton must expose "
            "an inspectable Python signature"
        ) from err
    try:
        signature.bind(object(), "kernel_name", "source_code", "cuda")
    except TypeError as err:
        raise ValueError(
            "triton_tvm_inductor_private_api_guard: AsyncCompile.triton signature "
            "must accept (async_compile, kernel_name, source_code, device_str)"
        ) from err
    return {"async_compile_triton_signature": str(signature)}


def _record_private_api_guard_error_once(
    session: TritonTVMInductorSession,
    err: Exception,
) -> None:
    if getattr(err, "_triton_tvm_guard_recorded", False):
        return
    session._record_private_api_guard_error(err)  # pylint: disable=protected-access
    try:
        setattr(err, "_triton_tvm_guard_recorded", True)
    except Exception:  # pylint: disable=broad-except
        pass


class _TritonTVMInductorKernel:
    def __init__(
        self,
        *,
        session: TritonTVMInductorSession,
        record: dict[str, Any],
        artifact: TritonTVMArtifact,
        async_compile,
        original_triton,
        kernel_name: str,
        source_code: str,
        device_str: str,
    ):
        self.session = session
        self.record = record
        self.artifact = artifact
        self.async_compile = async_compile
        self.original_triton = original_triton
        self.kernel_name = kernel_name
        self.source_code = source_code
        self.device_str = device_str

    def run(  # pylint: disable=unused-argument
        self,
        *args,
        stream,
        benchmark_run=False,
        **kwargs,
    ):
        """Launch the TVM artifact using PyTorch tensors and Inductor's raw stream."""
        try:
            if kwargs:
                raise ValueError(
                    "M5 Triton TVM Inductor launcher does not support keyword "
                    f"runtime arguments: {sorted(kwargs)}"
                )
            tvm_args, device_index = _torch_runtime_args_to_tvm(
                args, self.artifact.meta
            )
            dev = _tvm_cuda_device(device_index)
            if stream is not None:
                dev.set_raw_stream(int(stream))
            try:
                result = self.artifact.run(tvm_args)
            finally:
                if stream is not None:
                    dev.set_raw_stream(0)
        except Exception as err:  # pylint: disable=broad-except
            status = status_from_exception(err)
            self.record["runtime_status"] = status
            self.record["translate_status"] = status
            self.record["native_fallback_count"] = self.record.get("native_fallback_count", 0)
            self.session.counters["runtime_errors"] += 1
            self.session.write_report()
            raise

        self.session._record_run(self.record)  # pylint: disable=protected-access
        return result


def audit_inductor_ttir(
    ttir_or_artifact: str | TTIRArtifact,
    *,
    case_name: str = "",
    kernel_name: str = "",
    source: str = "",
    signature: dict[str, str] | None = None,
    constexprs: dict[str, Any] | None = None,
    contract: str = "pointwise_flat",
) -> dict[str, Any]:
    """Summarize one Inductor TTIR module and classify translator support."""
    if isinstance(ttir_or_artifact, TTIRArtifact):
        ttir = ttir_or_artifact.ttir
        kernel_name = kernel_name or ttir_or_artifact.kernel_name
        signature = signature or ttir_or_artifact.signature
        constexprs = constexprs or ttir_or_artifact.constexprs
    else:
        ttir = ttir_or_artifact

    record: dict[str, Any] = {
        "corpus": "m3_inductor_pointwise",
        "case_name": case_name or kernel_name,
        "kernel_name": kernel_name,
        "contract": contract,
        "source_hash": _sha256(source) if source else "",
        "ttir_hash": _sha256(ttir),
        "signature": dict(signature or {}),
        "constexprs": _jsonable(dict(constexprs or {})),
        "unique_ops": [],
        "op_counts": {},
        "types": [],
        "raw_load_store_attrs": [],
        "load_count": 0,
        "store_count": 0,
        "mask_forms": [],
        "indexing_summary": {},
        "translate_status": {"ok": False, "bucket": "not_run"},
    }

    try:
        graph = TTIRReader().read(ttir)
    except Exception as err:  # pylint: disable=broad-except
        record["translate_status"] = _error_status("reader_error", err)
        return record

    record.update(_graph_coverage(graph))
    try:
        translate_ttir(ttir, grid=(1,), contract=contract)
        record["translate_status"] = make_report_status(ok=True, bucket="translated")
    except UnsupportedTTIROpError as err:
        record["translate_status"] = _error_status("unsupported_ttir_op", err)
    except (TritonTVMContractError, UnsupportedContractError) as err:
        record["translate_status"] = _error_status("contract_error", err)
    except UnsupportedTargetPolicyError as err:
        record["translate_status"] = _error_status("target_policy_error", err)
    except Exception as err:  # pylint: disable=broad-except
        record["translate_status"] = _error_status("translate_other_error", err)
    return record


def audit_inductor_kernel(
    kernel: InductorKernel,
    *,
    ttir_dir: str | Path | None = None,
    contract: str = "pointwise_flat",
) -> dict[str, Any]:
    """Lower and audit a loaded Inductor pointwise kernel."""
    dump_path = None
    if ttir_dir is not None:
        dump_path = Path(ttir_dir) / f"{_safe_name(kernel.case_name)}_{kernel.kernel_name}.ttir"
    try:
        artifact = lower_inductor_kernel_to_ttir(kernel, dump_path=dump_path)
    except Exception as err:  # pylint: disable=broad-except
        return {
            "corpus": "m3_inductor_pointwise",
            "case_name": kernel.case_name,
            "kernel_name": kernel.kernel_name,
            "contract": contract,
            "source_hash": _sha256(kernel.source),
            "ttir_hash": "",
            "signature": dict(kernel.signature),
            "constexprs": _jsonable(kernel.constexprs),
            "unique_ops": [],
            "op_counts": {},
            "types": [],
            "raw_load_store_attrs": [],
            "load_count": 0,
            "store_count": 0,
            "mask_forms": [],
            "indexing_summary": {},
            "translate_status": _error_status("lowering_error", err),
        }
    return audit_inductor_ttir(
        artifact,
        case_name=kernel.case_name,
        kernel_name=kernel.kernel_name,
        source=kernel.source,
        signature=kernel.signature,
        constexprs=kernel.constexprs,
        contract=contract,
    )


def run_inductor_audit(
    sources: list[InductorTritonSource],
    *,
    out_dir: str | Path,
    min_kernels: int = 20,
    contract: str = "pointwise_flat",
    extra_errors: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Audit extracted Inductor sources and write kernel, TTIR, and report files."""
    out_path = Path(out_dir)
    kernel_dir = out_path / "kernels"
    ttir_dir = out_path / "ttir"
    kernel_dir.mkdir(parents=True, exist_ok=True)
    ttir_dir.mkdir(parents=True, exist_ok=True)

    records: list[dict[str, Any]] = []
    filtered: list[dict[str, Any]] = []
    errors = list(extra_errors or [])

    for source in sources:
        kernel_path = kernel_dir / f"{_safe_name(source.case_name)}_{source.kernel_name}.py"
        kernel_path.write_text(source.source, encoding="utf-8")
        try:
            kernel = load_inductor_kernel(source)
        except Exception as err:  # pylint: disable=broad-except
            errors.append(
                {
                    "case_name": source.case_name,
                    "kernel_name": source.kernel_name,
                    "bucket": "load_error",
                    "error_type": type(err).__name__,
                    "message": str(err),
                }
            )
            continue
        if not is_inductor_pointwise_kernel(kernel):
            filtered.append(
                {
                    "case_name": kernel.case_name,
                    "kernel_name": kernel.kernel_name,
                    "grid_type": kernel.inductor_meta.get("grid_type"),
                    "num_reduction": kernel.inductor_meta.get("num_reduction"),
                    "atomic_add_found": kernel.inductor_meta.get("atomic_add_found"),
                }
            )
            continue
        record = audit_inductor_kernel(kernel, ttir_dir=ttir_dir, contract=contract)
        record["kernel_source_path"] = str(kernel_path)
        ttir_path = ttir_dir / f"{_safe_name(kernel.case_name)}_{kernel.kernel_name}.ttir"
        record["ttir_path"] = str(ttir_path)
        records.append(record)

    if len(records) < min_kernels:
        raise RuntimeError(
            f"M3 Inductor audit collected {len(records)} pointwise kernels, "
            f"below required minimum {min_kernels}"
        )

    report = build_audit_report(records, filtered=filtered, errors=errors)
    write_audit_report(report, out_path)
    return report


def build_audit_report(
    kernel_records: list[dict[str, Any]],
    *,
    filtered: list[dict[str, Any]] | None = None,
    errors: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Build the JSON-serializable M3 audit report payload."""
    records = []
    for record in kernel_records:
        normalized = dict(record)
        normalized.setdefault("corpus", "m3_inductor_pointwise")
        normalized.setdefault("contract", "")
        records.append(normalized)
    return build_capability_report(
        records,
        purpose="m3 inductor pointwise ttir coverage audit",
        corpus="m3_inductor_pointwise",
        filtered=filtered,
        errors=errors,
    )


def write_audit_report(report: dict[str, Any], out_dir: str | Path) -> None:
    """Write ``report.json`` and ``report.md`` for an M3 audit run."""
    write_capability_report(
        report,
        out_dir,
        markdown_title="M3 Inductor Pointwise TTIR Audit",
        footer_lines=_pre_m5_boundary_lines(),
    )


def render_audit_markdown(report: dict[str, Any]) -> str:
    """Render a compact Markdown view of the M3 audit report."""
    return render_capability_markdown(
        report,
        title="M3 Inductor Pointwise TTIR Audit",
        footer_lines=_pre_m5_boundary_lines(),
    )


