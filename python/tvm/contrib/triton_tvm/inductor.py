def _literal_string(node: ast.AST) -> str:
    try:
        value = ast.literal_eval(node)
    except (ValueError, SyntaxError):
        return ""
    return value if isinstance(value, str) else ""


def _first_triton_jit_function_name(source: str) -> str:
    tree = ast.parse(source)
    saw_jit = False
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        if any(_decorator_mentions_triton_jit(decorator) for decorator in node.decorator_list):
            return node.name
    return ""


def _decorator_mentions_triton_jit(node: ast.AST) -> bool:
    if isinstance(node, ast.Attribute) and node.attr == "jit":
        return True
    if isinstance(node, ast.Call):
        return _decorator_mentions_triton_jit(node.func)
    return False


def _torch_runtime_args_to_tvm(args: tuple[Any, ...], meta) -> tuple[list[Any], int]:
    import tvm  # pylint: disable=import-outside-toplevel

    if len(args) != len(meta.abi):
        raise ValueError(f"Expected {len(meta.abi)} runtime arguments, got {len(args)}")

    tvm_args: list[Any] = []
    device_index = 0
    for arg, spec in zip(args, meta.abi, strict=True):
        if spec["kind"] == "pointer":
            device = getattr(arg, "device", None)
            if getattr(device, "type", None) == "cuda" and device.index is not None:
                device_index = int(device.index)
            tvm_args.append(tvm.runtime.from_dlpack(arg))
        else:
            tvm_args.append(arg)
    return tvm_args, device_index


