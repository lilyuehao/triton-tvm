"""TorchInductor pointwise TTIR audit and experimental hook helpers.

The audit path collects Triton kernels generated by TorchInductor, lowers them
to TTIR, summarizes the TTIR surface area, and classifies support through
canonical Triton TVM contracts.

The M5 hook path is intentionally experimental.  It wraps TorchInductor's
``AsyncCompile.triton`` call site during one ``torch.compile`` invocation and
routes currently-supported pointwise kernels through TVM, with native Triton
fallback for unsupported kernels.
"""

